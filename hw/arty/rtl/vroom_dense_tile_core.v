`default_nettype none
// Core-clock integration of the tile executor and four actor-private buffers.
// FP32 arithmetic, model descriptors, DDR/CDC, and controller I/O stay external.
module vroom_dense_tile_core #(
    parameter integer LANES = 12
) (
    input wire clk,
    input wire reset,
    input wire context_valid,
    output wire context_accept,
    input wire context_actor,
    input wire [31:0] context_job,
    input wire [1:0] context_layer,
    input wire [8:0] context_inputs,
    input wire [8:0] context_outputs,
    input wire input_valid,
    output wire input_ready,
    input wire [31:0] input_data,
    input wire bias_valid,
    output wire bias_ready,
    input wire [31:0] bias_data,
    output wire [1:0] context_ready,
    output wire [1:0] context_complete,
    input wire command_valid,
    output wire command_ready,
    input wire command_actor,
    input wire [31:0] command_job,
    input wire [1:0] command_layer,
    input wire [1:0] command_buffer,
    input wire [31:0] command_tag,
    input wire [7:0] command_row,
    input wire [7:0] command_rows,
    input wire [7:0] command_column,
    input wire [2:0] command_columns,
    output wire done_valid,
    input wire done_ready,
    output wire active_actor,
    output wire [31:0] active_job,
    output wire [1:0] active_layer,
    output wire mac_valid,
    input wire mac_ready,
    output wire [31:0] mac_tag,
    output wire [LANES-1:0] mac_mask,
    output wire [31:0] mac_input,
    output wire [LANES*32-1:0] mac_weight,
    output wire [LANES*32-1:0] mac_accumulator,
    input wire mac_response_valid,
    output wire mac_response_ready,
    input wire [31:0] mac_response_tag,
    input wire [LANES*32-1:0] mac_response_data,
    input wire result_valid,
    output wire result_ready,
    input wire result_actor,
    input wire [7:0] result_row,
    input wire [LANES-1:0] result_mask,
    output wire result_response_valid,
    output wire [LANES-1:0] result_response_mask,
    output wire [LANES*32-1:0] result_response_data,
    output wire [31:0] result_response_job,
    output wire [1:0] result_response_layer,
    output wire [3:0] state,
    output wire [3:0] fault_code,
    input wire load_valid,
    output wire load_ready,
    input wire [1:0] load_buffer,
    input wire [31:0] load_tag,
    input wire [9:0] load_words,
    input wire dma_valid,
    output wire dma_ready,
    input wire [1:0] dma_buffer,
    input wire [31:0] dma_tag,
    input wire [127:0] dma_data,
    input wire dma_last,
    input wire status_valid,
    output wire status_ready,
    input wire [1:0] status_buffer,
    input wire [31:0] status_tag,
    input wire status_ok,
    input wire [11:0] status_bytes,
    output wire [7:0] buffer_states,
    output wire [3:0] buffer_faults,
    output wire [15:0] buffer_fault_codes,
    output wire fault
);
    wire engine_fault, tile_fault;
    wire load_r, dma_r, status_r;
    assign fault = engine_fault || tile_fault;
    assign load_ready = load_r && !fault;
    assign dma_ready = dma_r && !fault;
    assign status_ready = status_r && !fault;
    wire tile_acquire_valid;
    wire tile_acquire_ready;
    wire [1:0] tile_buffer;
    wire [31:0] tile_tag;
    wire tile_release_valid;
    wire tile_release_ready;
    wire tile_read_valid;
    wire tile_read_ready;
    wire [8:0] tile_read_base;
    wire [LANES-1:0] tile_read_mask;
    wire tile_response_valid;
    wire [LANES-1:0] tile_response_mask;
    wire [LANES*32-1:0] tile_response_data;
    vroom_dense_tile #(.LANES(LANES)) engine (
        .clk(clk),
        .reset(reset),
        .context_valid(context_valid),
        .context_accept(context_accept),
        .context_actor(context_actor),
        .context_job(context_job),
        .context_layer(context_layer),
        .context_inputs(context_inputs),
        .context_outputs(context_outputs),
        .input_valid(input_valid),
        .input_ready(input_ready),
        .input_data(input_data),
        .bias_valid(bias_valid),
        .bias_ready(bias_ready),
        .bias_data(bias_data),
        .context_ready(context_ready),
        .context_complete(context_complete),
        .command_valid(command_valid),
        .command_ready(command_ready),
        .command_actor(command_actor),
        .command_job(command_job),
        .command_layer(command_layer),
        .command_buffer(command_buffer),
        .command_tag(command_tag),
        .command_row(command_row),
        .command_rows(command_rows),
        .command_column(command_column),
        .command_columns(command_columns),
        .done_valid(done_valid),
        .done_ready(done_ready),
        .active_actor(active_actor),
        .active_job(active_job),
        .active_layer(active_layer),
        .tile_acquire_valid(tile_acquire_valid),
        .tile_acquire_ready(tile_acquire_ready),
        .tile_buffer(tile_buffer),
        .tile_tag(tile_tag),
        .tile_release_valid(tile_release_valid),
        .tile_release_ready(tile_release_ready),
        .tile_read_valid(tile_read_valid),
        .tile_read_ready(tile_read_ready),
        .tile_read_base(tile_read_base),
        .tile_read_mask(tile_read_mask),
        .tile_response_valid(tile_response_valid),
        .tile_response_mask(tile_response_mask),
        .tile_response_data(tile_response_data),
        .tile_fault(tile_fault),
        .mac_valid(mac_valid),
        .mac_ready(mac_ready),
        .mac_tag(mac_tag),
        .mac_mask(mac_mask),
        .mac_input(mac_input),
        .mac_weight(mac_weight),
        .mac_accumulator(mac_accumulator),
        .mac_response_valid(mac_response_valid),
        .mac_response_ready(mac_response_ready),
        .mac_response_tag(mac_response_tag),
        .mac_response_data(mac_response_data),
        .result_valid(result_valid),
        .result_ready(result_ready),
        .result_actor(result_actor),
        .result_row(result_row),
        .result_mask(result_mask),
        .result_response_valid(result_response_valid),
        .result_response_mask(result_response_mask),
        .result_response_data(result_response_data),
        .result_response_job(result_response_job),
        .result_response_layer(result_response_layer),
        .state(state),
        .fault(engine_fault),
        .fault_code(fault_code)
    );
    vroom_weight_tiles #(.LANES(LANES)) tiles (
        .clk(clk), .reset(reset),
        .load_valid(load_valid && !fault), .load_ready(load_r), .load_buffer(load_buffer), .load_tag(load_tag), .load_words(load_words),
        .dma_valid(dma_valid && !fault), .dma_ready(dma_r), .dma_buffer(dma_buffer), .dma_tag(dma_tag), .dma_data(dma_data), .dma_last(dma_last),
        .status_valid(status_valid && !fault), .status_ready(status_r), .status_buffer(status_buffer), .status_tag(status_tag), .status_ok(status_ok), .status_bytes(status_bytes),
        .acquire_valid(tile_acquire_valid), .acquire_ready(tile_acquire_ready), .acquire_buffer(tile_buffer), .acquire_tag(tile_tag),
        .release_valid(tile_release_valid), .release_ready(tile_release_ready), .release_buffer(tile_buffer), .release_tag(tile_tag),
        .read_valid(tile_read_valid), .read_ready(tile_read_ready), .read_buffer(tile_buffer), .read_base(tile_read_base), .read_mask(tile_read_mask),
        .response_valid(tile_response_valid), .response_mask(tile_response_mask), .response_data(tile_response_data),
        .states(buffer_states), .fault(tile_fault), .fault_buffers(buffer_faults), .fault_codes(buffer_fault_codes)
    );
endmodule
`default_nettype wire
